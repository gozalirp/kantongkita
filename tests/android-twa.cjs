const assert = require('node:assert/strict');
const fs = require('node:fs');
const assetlinks = require('../scripts/android-assetlinks.cjs');
const read = p => fs.readFileSync(p, 'utf8');
for (const bad of [[], null, ['AA:BB'], ['x'.repeat(95)], ['AA:'.repeat(32)]]) assert.throws(() => assetlinks(bad));
const fp = Array(32).fill('ab').join(':');
const links = assetlinks([fp, fp]);
assert.equal(links[0].target.package_name, 'com.savingduit.app');
assert.deepEqual(links[0].target.sha256_cert_fingerprints, [fp.toUpperCase()]);
const manifest = read('android-twa/app/src/main/AndroidManifest.xml');
assert(manifest.includes('https://moneyplanner.darmintompel.my.id/'));
assert(manifest.includes('android:usesCleartextTraffic="false"'));
assert(!manifest.includes('android.permission.READ_'));
const build = read('android-twa/app/build.gradle');
assert(build.includes("applicationIdSuffix '.debug'"));
assert(build.includes('throw new GradleException'));
assert(build.includes('minSdk 24'));
assert(manifest.includes('com.savingduit.app.MainActivity'));
assert(manifest.includes('android.support.customtabs.action.CustomTabsService'));
assert(manifest.includes('@style/Theme.KantongKita.Launcher'));
const launcher = read('android-twa/app/src/main/java/com/savingduit/app/MainActivity.java');
assert(launcher.includes('super.launchTwa()'));
assert(launcher.includes('catch (RuntimeException error)'));
assert(launcher.includes('Log.e('));
assert(launcher.includes('intent.setPackage("com.android.chrome")'));
assert(!launcher.includes('WebView'));
const ci = read('.github/workflows/build-apk.yml');
assert(!ci.includes('cap sync'));
assert(ci.includes('set -euo pipefail'));
assert(ci.includes(':app:assembleRelease :app:bundleRelease'));
assert(ci.includes('if-no-files-found: error'));
assert(fs.readFileSync('public/icon-512.png').equals(fs.readFileSync('android-twa/app/src/main/res/drawable/icon.png')));
console.log('PASS: Android TWA static config, separate debug identity, signing gate and fingerprint validation (not an Android build).');
