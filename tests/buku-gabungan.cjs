const assert = require('node:assert/strict');
const fs = require('node:fs');
const { JSDOM } = require('jsdom');
const dom = new JSDOM('<body></body>', { url: 'http://localhost', runScripts: 'outside-only' });
const w = dom.window;
for (const file of ['util.js', 'store.js', 'keluarga-mode.js', 'buku-gabungan.js']) w.eval(fs.readFileSync('public/js/' + file, 'utf8'));
const B = w.Buku, S = w.S;
const p = S.normalize({ wallets: [{ id: 'same', name: 'Rahasia', initial: 100 }], categories: [{ id: 'c', name: 'Pribadi' }], transactions: [{ id: 't', walletId: 'same', categoryId: 'c', type: 'out', amount: 10 }] });
const f = S.normalize({ wallets: [{ id: 'same', name: 'Bersama', initial: 200 }], categories: [{ id: 'c', name: 'Makan' }], transactions: [{ id: 't', walletId: 'same', categoryId: 'c', type: 'out', amount: 20 }] });
const before = JSON.stringify([p, f]);
const both = B.gabung(p, f, 'semua');
assert.equal(both.wallets.length, 2);
assert.notEqual(both.wallets[0].id, both.wallets[1].id);
assert.equal(both.transactions[1].walletId, both.wallets[1].id);
assert.equal(both.transactions[1]._id, 't');
assert.equal(B.gabung(p, f, 'pribadi').wallets.length, 1);
assert.equal(B.gabung(p, f, 'keluarga').wallets[0]._sumber, 'keluarga');
assert.equal(JSON.stringify([p, f]), before);
w.K.nama = 'owner'; w.K.terbuka = true;
B.akun = 'owner'; B.keluarga = f; B.revisi = 7;
let calls = 0;
w.fetch = async (_, options) => {
  calls++;
  const data = JSON.parse(options.body);
  assert.equal(data.revision, 7);
  assert.equal(data.book.wallets.length, 1);
  assert.equal(data.book.wallets[0].name, 'Bersama');
  assert(!JSON.stringify(data).includes('Rahasia'));
  assert(!JSON.stringify(data).includes('_sumber'));
  return { ok: true, status: 200, json: async () => ({ ok: true }) };
};
(async () => {
  await B.simpan(f, 7);
  assert.equal(calls, 1); assert.equal(B.revisi, 8);
  await assert.rejects(() => B.simpan(f, 7), /berubah/);
  B.sibuk = true;
  await assert.rejects(() => B.simpan(f, 8), /Tunggu/);
  B.sibuk = false;
  w.fetch = async () => ({ ok: false, status: 409 });
  await assert.rejects(() => B.simpan(f, 8), /Pasangan/);
  assert.equal(B.revisi, 8); assert.equal(B.sibuk, false);
  w.K.nama = 'different';
  await assert.rejects(() => B.simpan(f, 8), /Muat ulang/);
  console.log('PASS: isolation, ID collisions, filtering, payload privacy, revision conflicts, account checks');
  dom.window.close();
})().catch(e => { console.error(e); process.exitCode = 1; dom.window.close(); });
