const assert = require('node:assert/strict');
const fs = require('node:fs');
const { JSDOM } = require('jsdom');
const dom = new JSDOM('<main id="view"></main>', { url: 'http://localhost/', runScripts: 'outside-only' });
const w = dom.window;
for (const file of ['util.js', 'store.js', 'views.js']) w.eval(fs.readFileSync('public/js/' + file, 'utf8'));
const { V, S } = w;
const $ = id => w.document.getElementById(id);
w.App = { db: S.seedDB(), render() { $('view').innerHTML = V.transaksi(); V.transaksiBind(); } };
w.U.today = () => '2024-02-29';
$('view').innerHTML = '<label for="g-due">Tenggat</label><input type="date" id="g-due" value=""><input type="month" id="rk-ym" value="2024-02" aria-label="Bulan rekap">';
V.bindCalendars(); V.bindCalendars();
assert.equal(w.document.querySelectorAll('.calendar-toggle').length, 2, 'binding is idempotent');
assert.equal($('g-due-toggle').textContent, 'Pilih tanggal');
assert.equal(w.document.querySelector('label').htmlFor, 'g-due-toggle');
let changed = 0; $('g-due').onchange = () => changed++;
$('g-due-toggle').click();
assert(!$('g-due-calendar').hidden);
assert.equal(w.document.querySelectorAll('#g-due-calendar [data-date]').length, 29);
w.document.querySelector('#g-due-calendar [data-date="2024-02-29"]').click();
assert.equal($('g-due').value, '2024-02-29');
assert.equal(changed, 1); assert($('g-due-calendar').hidden);
$('g-due-toggle').click();
w.document.querySelector('#g-due-calendar .calendar-clear').click();
assert.equal($('g-due').value, '');
$('g-due-toggle').click();
let day = w.document.querySelector('#g-due-calendar [data-date="2024-02-29"]');
day.dispatchEvent(new w.KeyboardEvent('keydown', { key: 'ArrowRight', bubbles: true }));
assert.equal(w.document.activeElement.dataset.date, '2024-03-01');
w.document.activeElement.dispatchEvent(new w.KeyboardEvent('keydown', { key: 'Escape', bubbles: true }));
assert($('g-due-calendar').hidden);
assert.equal(w.document.activeElement, $('g-due-toggle'));
$('rk-ym-toggle').click();
assert.equal(w.document.querySelectorAll('#rk-ym-calendar [data-date]').length, 12);
w.document.querySelector('#rk-ym-calendar [data-year="1"]').click();
w.document.querySelector('#rk-ym-calendar [data-date="2025-10"]').click();
assert.equal($('rk-ym').value, '2025-10');
assert.equal($('rk-ym-toggle').textContent, 'Oktober 2025');
V.state.transaksi.preset = 'today'; w.App.render();
assert($('tx-date').hidden);
$('tx-date-toggle').click();
w.document.querySelector('#tx-date-calendar [data-date="2024-02-15"]').click();
assert.equal(V.state.transaksi.date, '2024-02-15', 'daily filter receives selected calendar date');
assert.equal($('tx-date-toggle').textContent, '15 Feb 2024');
dom.window.close();
console.log('Shared calendar: date/month, leap day, clear, keyboard, change events passed');
