const assert = require('node:assert/strict');
const fs = require('node:fs');
const { JSDOM } = require('jsdom');
const html = fs.readFileSync('public/index.html', 'utf8').replace(/<script src="[^"]+"><\/script>/g, '');
const dom = new JSDOM(html, { url: 'http://localhost/', runScripts: 'outside-only', pretendToBeVisual: true });
const w = dom.window;
w.fetch = async () => { throw Error('offline'); };
for (const file of ['util.js', 'store.js', 'gdrive.js', 'views.js', 'app.js']) w.eval(fs.readFileSync('public/js/' + file, 'utf8'));
w.App.init();
for (const file of ['keluarga-mode.js', 'buku-gabungan.js']) w.eval(fs.readFileSync('public/js/' + file, 'utf8'));
const { App, V, S, K, Buku: B } = w;
const $ = id => w.document.getElementById(id);
K.nama = 'owner'; K.terbuka = true; B.akun = 'owner'; B.revisi = 2;
B.keluarga = S.seedDB(); B.keluarga.wallets[0].name = 'Dompet Bersama';
const pribadi = JSON.stringify(App.db);
let payload;
w.fetch = async (url, options) => {
  assert.equal(url, '/api/family/save'); payload = JSON.parse(options.body);
  return { ok: true, status: 200, json: async () => ({ ok: true }) };
};
(async () => {
  App.render();
  assert($('undang-pasangan'));
  assert.equal(w.document.querySelectorAll('.buku-kontrol .seg button').length, 3);
  V.txForm();
  assert($('buku-dompet'));
  $('buku-dompet').value = B.id('keluarga', B.keluarga.wallets[0].id);
  await $('buku-lanjut').onclick();
  assert($('modal-body').textContent.includes('Terlihat oleh keluarga'));
  assert(!$('f-rcp'));
  $('f-amount').value = '5000'; $('f-note').value = 'Makan bersama';
  await $('f-save').onclick();
  assert.equal(payload.book.transactions.length, 1);
  assert.equal(payload.book.transactions[0].amount, 5000);
  assert.equal(payload.book.transactions[0].walletId, B.keluarga.wallets[0].id);
  assert.equal(payload.book.transactions[0].note, 'Makan bersama');
  assert.equal(JSON.stringify(App.db), pribadi);
  assert.equal(payload.revision, 2);
  // Edit through the actual combined-row control; IDs can overlap between books.
  const row = w.document.querySelector('[data-tx]');
  const btn = row.querySelector('[aria-label="Ubah"]');
  w.eval(btn.getAttribute('onclick'));
  assert.equal($('f-note').value, 'Makan bersama');
  $('f-amount').value = '6000'; await $('f-save').onclick();
  assert.equal(payload.book.transactions.length, 1);
  assert.equal(payload.book.transactions[0].amount, 6000);
  assert.equal(JSON.stringify(App.db), pribadi);
  // All four pages use the same isolated book and retain payment markers.
  V.budgetForm(); $('buku-sumber').value = 'keluarga'; $('buku-pilih').click();
  $('b-cat').value = B.keluarga.categories.find(c => c.type === 'out').id; $('b-limit').value = '100000'; await $('b-save').onclick();
  assert.equal(B.keluarga.budgets.length, 1);
  V.goalForm(); $('buku-sumber').value = 'keluarga'; $('buku-pilih').click();
  $('g-name').value = 'Liburan'; $('g-target').value = '1000000'; await $('g-save').onclick();
  const goal = B.id('keluarga', B.keluarga.goals[0].id);
  V.goalAdd(goal); $('ga-amt').value = '10000'; await $('ga-save').onclick();
  assert.equal(B.keluarga.goals[0].saved, 10000);
  V.goalAdd(goal, true); $('ga-amt').value = '3000'; await $('ga-save').onclick();
  assert.equal(B.keluarga.goals[0].saved, 7000);
  V.subForm(); $('buku-sumber').value = 'keluarga'; $('buku-pilih').click();
  $('s-name').value = 'Internet'; $('s-amount').value = '20000';
  $('s-wallet').value = B.keluarga.wallets[0].id; await $('s-save').onclick();
  const sub = B.id('keluarga', B.keluarga.subscriptions[0].id);
  await V.subPay(sub);
  assert.equal(B.keluarga.transactions.length, 2);
  const combined = B.data();
  assert(S.subPaidIn(combined, combined.subscriptions[0], w.U.monthOf(w.U.today())));
  await V.subPay(sub); assert.equal(B.keluarga.transactions.length, 2);
  await V.subToggle(sub); assert.equal(B.keluarga.subscriptions[0].active, false);
  V.confirm = async () => true;
  await V.subUnpay(sub, w.U.monthOf(w.U.today()));
  assert.equal(B.keluarga.transactions.length, 1);
  for (const page of ['rekap', 'anggaran', 'target', 'langganan']) {
    App.view = page; App.render();
    assert($('undang-pasangan'), page + ' has shared filters');
    assert(!w.document.body.textContent.includes('Pengelolaan catatan pribadi.'));
  }
  await V.budgetDelete(B.id('keluarga', B.keluarga.budgets[0].id));
  await V.goalDelete(goal); await V.subDelete(sub);
  assert.equal(B.keluarga.budgets.length + B.keluarga.goals.length + B.keluarga.subscriptions.length, 0);
  assert.equal(JSON.stringify(App.db), pribadi);
  // Invitation is an explicit click, never generated by rendering.
  w.fetch = async (url, options) => {
    assert.equal(url, '/api/family/invite'); assert.equal(options.method, 'POST');
    return { ok: true, json: async () => ({ code: 'test-invite' }) };
  };
  await B.undang($('undang-pasangan'));
  assert.equal($('undangan-kode').value, 'test-invite');
  assert($('undangan-kode').readOnly);
  console.log('PASS: combined dashboard, wallet routing, family create/edit isolation, invitation modal');
  dom.window.close(); process.exit(0);
})().catch(e => { console.error(e); dom.window.close(); process.exit(1); });
