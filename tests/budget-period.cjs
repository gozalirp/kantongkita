const assert = require('node:assert/strict');
const fs = require('node:fs');
const { JSDOM } = require('jsdom');
const dom = new JSDOM('<main></main><div id="modal-body"></div>', { url: 'http://localhost/', runScripts: 'outside-only' });
const w = dom.window;
for (const file of ['util.js', 'store.js', 'views.js']) w.eval(fs.readFileSync('public/js/' + file, 'utf8'));
const { S, V } = w;
w.U.today = () => '2026-11-03';
const db = S.seedDB(), cat = db.categories.find(c => c.type === 'out'), wallet = db.wallets[0];
db.transactions = [['2025-12-31', 100], ['2026-10-31', 200], ['2026-11-03', 300], ['2026-12-01', 400]].map(([date, amount], i) => ({ id: 'b' + i, date, amount, type: 'out', categoryId: cat.id, walletId: wallet.id }));
db.transactions.push({ ...db.transactions[0], id: 'income', type: 'in', amount: 9000 });
const budget = { id: 'budget', categoryId: cat.id, limit: 2000, period: 'all', note: '' };
db.budgets = [budget];
const snapshot = JSON.stringify(db);
assert.equal(S.budgetUsage(db, budget).used, 1000);
assert.equal(S.budgetUsage(db, budget, '2027-01-01').used, 1000);
assert.equal(S.budgetUsage(db, { ...budget, period: 'month' }).used, 300);
assert.equal(S.budgetUsage(db, { ...budget, period: 'year' }).used, 900);
assert.equal(S.budgetUsage(db, { ...budget, period: undefined }).used, 300);
assert.equal(S.budgetTotal(db).limit, 0, 'all-time budget is not monthly total');
assert.equal(JSON.stringify(db), snapshot, 'calculations never mutate financial data');
w.App = { db, saveAndRender() {} };
V.state.anggaran.period = 'all';
assert.match(V.anggaran(), /keseluruhan · tanpa reset/);
assert.match(V.anggaran(), /id="budget-period"/);
assert.match(V.anggaran(), /data-period="all" aria-pressed="true"/);
V.state.anggaran.period = 'month';
assert.doesNotMatch(V.anggaran(), /keseluruhan · tanpa reset/);
V.state.anggaran.period = 'all';
assert.match(V.anggaran(), /Pemakaian Anggaran Sesuai Periode/);
V.modal.open = ({ body, foot }) => { w.document.getElementById('modal-body').innerHTML = body + foot; };
V.modal.close = () => {};
V.toast = () => {};
V.budgetForm('budget');
const period = w.document.getElementById('b-period');
assert.equal(period.options.length, 3);
assert.equal(period.value, 'all', 'editing preserves all-time period');
w.document.getElementById('b-save').click();
assert.equal(db.budgets[0].period, 'all', 'all-time period persists');
dom.window.close();
console.log('PASS: budget monthly/yearly/all-time ranges, no reset, monthly summary isolation and form roundtrip');
