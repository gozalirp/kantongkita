const fs = require('node:fs');
const assert = require('node:assert/strict');
const { JSDOM } = require('jsdom');
const w = new JSDOM('', { runScripts: 'outside-only' }).window;
for (const f of ['util.js','store.js']) w.eval(fs.readFileSync('public/js/'+f,'utf8'));
const db = w.S.seedDB(); db.wallets[0].initial = 1000; db.transactions=[];
const id=db.wallets[0].id;
const g={id:'goal',saved:500,history:[]}; db.goals=[g];
assert.equal(w.S.walletBalance(db,id),1000,'old savings never deducted retroactively');
w.S.goalTransfer(db,g,id,300,false);
assert.equal(g.saved,800); assert.equal(w.S.walletBalance(db,id),700);
w.S.goalTransfer(db,g,id,100,true);
assert.equal(g.saved,700); assert.equal(w.S.walletBalance(db,id),800);
assert.equal(db.transactions.length,0,'not income or expense');
const before=JSON.stringify(db);
assert.throws(()=>w.S.goalTransfer(db,g,id,900,false),/tidak cukup/);
assert.throws(()=>w.S.goalTransfer(db,g,id,800,true),/tidak cukup/);
assert.throws(()=>w.S.goalTransfer(db,g,'foreign',1,false),/dompet/);
assert.equal(JSON.stringify(db),before,'invalid transfers mutate nothing');
assert.equal(w.S.walletBalance(w.S.normalize(JSON.parse(before)),id),800);
w.close(); console.log('PASS: goal transfers, balance, legacy savings, persistence and invalid-write guards');
